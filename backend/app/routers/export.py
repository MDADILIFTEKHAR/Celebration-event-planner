import json
from fastapi import APIRouter, HTTPException, Path, Body, Response
from ..models.schemas import EventPlan
from ..database import get_event_record, save_event_record

router = APIRouter(prefix="/api/events", tags=["export"])

@router.get("/{event_id}/export/json")
def export_plan_json(event_id: str = Path(...)):
    """Exports the entire celebration plan as a downloadable JSON file."""
    record = get_event_record(event_id)
    if not record:
        raise HTTPException(status_code=404, detail="Celebration plan not found.")

    plan = EventPlan.model_validate(record)
    content = json.dumps(plan.model_dump(), indent=2)
    filename = f"{plan.requirements.title.lower().replace(' ', '_')}_plan.json"

    return Response(
        content=content,
        media_type="application/json",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )

@router.post("/import/json", response_model=EventPlan)
def import_plan_json(payload: dict = Body(...)):
    """Imports an exported celebration plan JSON, validates schema, and saves to database."""
    try:
        plan = EventPlan.model_validate(payload)
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Invalid event plan JSON format: {str(e)}")

    save_event_record(
        event_id=plan.id,
        title=plan.requirements.title,
        celebration_type=plan.requirements.celebration_type,
        created_at=plan.created_at,
        updated_at=plan.updated_at,
        data=plan.model_dump()
    )
    return plan

@router.get("/{event_id}/export/summary")
def export_plan_summary(event_id: str = Path(...)):
    """Generates a structured printable summary of the actual celebration plan."""
    record = get_event_record(event_id)
    if not record:
        raise HTTPException(status_code=404, detail="Celebration plan not found.")

    plan = EventPlan.model_validate(record)
    reqs = plan.requirements
    b = plan.budget

    lines = []
    lines.append(f"# {reqs.title.upper()} - OFFICIAL CELEBRATION PLAN")
    lines.append(f"Generated by Celebration Event Planner AI | Mode: {plan.ai_mode_used}\n")
    lines.append(f"**Date:** {reqs.event_date} | **Start Time:** {reqs.start_time} | **Duration:** {reqs.duration_hours} hrs")
    lines.append(f"**Location:** {reqs.location or 'Venue TBD'} | **Setting:** {reqs.venue_preference.capitalize()}")
    lines.append(f"**Guests:** {reqs.guest_count} | **Budget:** {reqs.currency} {b.total_budget:,.2f} (Allocated: {reqs.currency} {b.total_allocated:,.2f})\n")

    lines.append("## 1. Budget Breakdown")
    for cat, total in b.category_totals.items():
        lines.append(f"- **{cat.replace('_', ' ').capitalize()}:** {reqs.currency} {total:,.2f}")
    lines.append(f"- **Contingency Buffer:** {reqs.currency} {b.contingency_amount:,.2f} ({b.contingency_percentage}%)")
    lines.append(f"- **Remaining Balance:** {reqs.currency} {b.remaining_budget:,.2f}\n")

    lines.append("## 2. Event Timeline")
    for t in plan.timeline:
        lines.append(f"- **{t.display_time}** ({t.duration_minutes}m): {t.title} - {t.description}")
    lines.append("")

    lines.append("## 3. Planning Checklist")
    for task in plan.checklist:
        status_box = "[x]" if task.status == "completed" else "[ ]"
        lines.append(f"- {status_box} Due {task.due_date}: {task.task} ({task.priority.upper()} priority)")
    lines.append("")

    lines.append("## 4. Recommendations & Atmosphere")
    for rec in plan.recommendations:
        lines.append(f"- **{rec.title}** ({rec.category.capitalize()}): {rec.description}")
        lines.append(f"  *Reason:* {rec.reason}")
    lines.append("")

    if plan.feasibility_flags or plan.identified_constraints:
        lines.append("## 5. Identified Constraints & Safeguards")
        for c in plan.identified_constraints:
            lines.append(f"- Constraint: {c}")
        for f in plan.feasibility_flags:
            lines.append(f"- Advisory Flag: {f}")

    return {"summary_markdown": "\n".join(lines)}
